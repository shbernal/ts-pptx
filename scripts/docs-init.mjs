// Scaffold the small-project documentation kit: the docs skill, docs.json navigation, and the
// four starter pages, plus the `docs:*` scripts in package.json.
//
// This is a bootstrap for a *fresh* repo. In this one it is effectively inert — every file it
// writes already exists, so a plain run reports `preserve:` for all of them — but it is kept so
// the kit stays reproducible and so the canonical script list has one home.
//
// Keep PACKAGE_SCRIPTS in step with package.json. It is not decorative: `addPackageScripts`
// rewrites any script whose command differs, so a stale entry here silently *downgrades* a real
// repo. That is not hypothetical — this file previously claimed `python3 scripts/docs-*.py` long
// after the scripts had moved behind a Node shim, so running `docs:init` would have broken the
// docs pipeline it exists to install.

