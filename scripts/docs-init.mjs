/** The display name templates are rendered with: the flag, else the literal, else package name. */
function projectName(root, explicit) {
	if (explicit) return explicit
	if (!PROJECT_NAME.includes('{{')) return PROJECT_NAME
	const packageJson = path.join(root, 'package.json')
	if (existsSync(packageJson)) {
		try {
			const name = String(JSON.parse(readFileSync(packageJson, 'utf8')).name ?? '').trim()
			if (name) return name.replace(/^@/, '').split('/').pop()
		} catch {
			/* fall through to the directory name */
		}
	}
	return path.basename(root)
}

function writeFile(root, relativePath, content, force, dryRun) {
	const target = path.join(root, relativePath)
	if (existsSync(target) && !force) return `preserve: ${relativePath}`
	if (dryRun) return `${existsSync(target) ? 'overwrite' : 'create'}: ${relativePath}`
	mkdirSync(path.dirname(target), { recursive: true })
	writeFileSync(target, content, 'utf8')
	return `write: ${relativePath}`
}

function addPackageScripts(root, dryRun) {
	const packageJsonPath = path.join(root, 'package.json')
	if (!existsSync(packageJsonPath)) return null

	const pkg = JSON.parse(readFileSync(packageJsonPath, 'utf8'))
	pkg.scripts ??= {}
	if (typeof pkg.scripts !== 'object' || Array.isArray(pkg.scripts))
		throw new Error('package.json scripts must be an object')

	let changed = false
	for (const [name, command] of Object.entries(PACKAGE_SCRIPTS)) {
		if (pkg.scripts[name] !== command) {
			pkg.scripts[name] = command
			changed = true
		}
	}
	if (!changed) return 'ok: package.json docs scripts already present'
	if (dryRun) return 'update: package.json docs scripts'
	writeFileSync(packageJsonPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8')
	return 'write: package.json docs scripts'
}

const { values } = parseArgs({
	options: {
		'project-name': { type: 'string' },
		force: { type: 'boolean', default: false },
		'dry-run': { type: 'boolean', default: false },
		'no-package-scripts': { type: 'boolean', default: false },
	},
})

const root = process.cwd()
const name = projectName(root, values['project-name'])
for (const [relativePath, template] of Object.entries(TEMPLATES)) {
	console.log(writeFile(root, relativePath, template.replaceAll('ts-pptx', name), values.force, values['dry-run']))
}
if (!values['no-package-scripts']) {
	const result = addPackageScripts(root, values['dry-run'])
	if (result) console.log(result)
}
